"""Machine-readable exports: STIX 2.1 bundles and plain block lists.

STIX bundles import into MISP, OpenCTI and most TIPs; block lists drop
straight into firewall or EDR deny lists.
"""

from __future__ import annotations

import json
import uuid
from datetime import datetime, timezone

from .config import APP_NAME, APP_VERSION

_NAMESPACE = uuid.UUID("6f1c2b0e-7d8a-4c55-9a51-3f2b8d1e0c47")
_HASH_KEYS = {"MD5": "MD5", "SHA1": "SHA-1", "SHA256": "SHA-256"}


def _ts(value=None) -> str:
    if value:
        try:
            dt = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
            if dt.tzinfo is None:
                dt = dt.astimezone(timezone.utc)
            return dt.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.000Z")
        except ValueError:
            pass
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.000Z")


def _quote(value: str) -> str:
    return value.replace("\\", "\\\\").replace("'", "\\'")


def stix_pattern(ioc: str, kind: str) -> str | None:
    v = _quote(ioc)
    if kind == "IP":
        return f"[ipv6-addr:value = '{v}']" if ":" in ioc else f"[ipv4-addr:value = '{v}']"
    if kind == "Domain":
        return f"[domain-name:value = '{v}']"
    if kind == "URL":
        return f"[url:value = '{v}']"
    if kind in _HASH_KEYS:
        return f"[file:hashes.'{_HASH_KEYS[kind]}' = '{v}']"
    return None


def stix_bundle(results: list[dict], *, risks=("High", "Medium", "Low"), author: str = "") -> str:
    """STIX 2.1 bundle with one Indicator per scored IOC (deduplicated)."""
    identity_id = f"identity--{uuid.uuid5(_NAMESPACE, author or APP_NAME)}"
    now = _ts()
    objects = [{
        "type": "identity", "spec_version": "2.1", "id": identity_id, "created": now, "modified": now,
        "name": author or APP_NAME, "identity_class": "individual" if author else "system",
    }]
    seen: set[str] = set()
    for r in reversed(results):  # newest result per IOC wins
        ioc, kind, risk = r.get("ioc"), r.get("type"), r.get("risk")
        if not ioc or ioc in seen or risk not in risks:
            continue
        pattern = stix_pattern(ioc, kind)
        if not pattern:
            continue
        seen.add(ioc)
        when = _ts(r.get("timestamp"))
        families = sorted({*(r.get("threatfox") or {}).get("families", []), *(r.get("urlhaus") or {}).get("threats", [])})
        obj = {
            "type": "indicator", "spec_version": "2.1",
            "id": f"indicator--{uuid.uuid5(_NAMESPACE, kind + ':' + ioc)}",
            "created": when, "modified": when, "created_by_ref": identity_id,
            "name": f"{risk} severity {kind}: {ioc}",
            "description": "; ".join(r.get("reasons") or []),
            "indicator_types": ["malicious-activity"] if risk in ("High", "Medium") else ["anomalous-activity"],
            "pattern": pattern, "pattern_type": "stix", "pattern_version": "2.1",
            "valid_from": when,
            "labels": [risk.lower()] + [f.lower() for f in families],
        }
        if isinstance(r.get("score"), int):
            obj["confidence"] = r["score"]
        objects.append(obj)
    bundle = {"type": "bundle", "id": f"bundle--{uuid.uuid4()}", "objects": objects}
    return json.dumps(bundle, indent=2)


def blocklist(results: list[dict], *, risks=("High", "Medium"), title: str = "") -> str:
    """Plain-text deny list grouped by type, one indicator per line."""
    groups: dict[str, list[str]] = {}
    for r in results:
        if r.get("risk") in risks and r.get("ioc") and r.get("type") in ("IP", "Domain", "URL", *_HASH_KEYS):
            bucket = groups.setdefault(r["type"], [])
            if r["ioc"] not in bucket:
                bucket.append(r["ioc"])
    lines = [
        f"# {title or 'Block list'}",
        f"# Generated by {APP_NAME} {APP_VERSION} on {datetime.now():%Y-%m-%d %H:%M}",
        f"# Severities: {', '.join(risks)} · {sum(len(v) for v in groups.values())} indicators",
    ]
    for kind in ("IP", "Domain", "URL", "SHA256", "SHA1", "MD5"):
        if groups.get(kind):
            lines += ["", f"# {kind}"] + groups[kind]
    return "\n".join(lines) + "\n"
